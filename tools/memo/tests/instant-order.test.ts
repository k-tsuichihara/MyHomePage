import { describe, expect, it } from 'vitest';
import { compareInstants, instantOrderKey } from '../src/instant-order';

describe('オフセット・マイクロ秒を保持した日時比較', () => {
  it.each([
    ['0001-01-01T00:00:00Z', 0n],
    ['0001-01-01T00:00:00+23:59', -86340000000n],
    ['1970-01-01T00:00:00Z', 62135596800000000n],
    ['1970-01-01T00:00:00.000001Z', 62135596800000001n],
  ] as const)('既知の基準値 %s', (value, expected) => {
    expect(instantOrderKey(value)).toBe(expected);
  });
  it.each([
    ['2026-10-26T09:00:00+09:00', '2026-10-26T00:00:00Z'],
    ['2026-10-25T23:00:00-01:00', '2026-10-26T00:00:00Z'],
    ['2026-10-26T00:00:00.1Z', '2026-10-26T00:00:00.100000+00:00'],
    ['2026-10-26T23:59:00+23:59', '2026-10-26T00:00:00Z'],
    ['2026-10-25T00:01:00-23:59', '2026-10-26T00:00:00Z'],
  ])('同じ瞬間の異なる表記を同値とする %s', (a, b) => {
    expect(compareInstants(a, b)).toBe(0);
  });
  it.each([
    ['0099-12-31T23:59:59.999999Z', '0100-01-01T00:00:00Z'],
    ['1900-02-28T23:59:59.999999Z', '1900-03-01T00:00:00Z'],
    ['2000-02-28T23:59:59.999999Z', '2000-02-29T00:00:00Z'],
    ['2100-02-28T23:59:59.999999Z', '2100-03-01T00:00:00Z'],
    ['9999-12-31T23:59:59.999998-23:59', '9999-12-31T23:59:59.999999-23:59'],
  ])('暦境界と1マイクロ秒差を保持する %s', (a, b) => {
    expect(instantOrderKey(b) - instantOrderKey(a)).toBe(1n);
    expect(compareInstants(a, b)).toBe(-1);
    expect(compareInstants(b, a)).toBe(1);
  });
  it.each([null, 0, '', '0000-01-01T00:00:00Z', '+010000-01-01T00:00:00Z',
    '1900-02-29T00:00:00Z', '2026-10-26T24:00:00Z', '2026-10-26T00:00:60Z',
    '2026-10-26T00:00:00.1234567Z', '2026-10-26T00:00:00+24:00',
    '2026-10-26T00:00:00+00:60', '2026-10-26t00:00:00z', ' 2026-10-26T00:00:00Z'])
  ('既存の日時受理契約に反する入力を拒否する %s', value => {
    expect(() => instantOrderKey(value)).toThrow();
  });
});
